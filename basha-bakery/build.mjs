// Basha Bakery & Restaurant — build script (esbuild).
//   npm run build  -> dist/index.html  (one self-contained file, deploy anywhere)
//   npm run dev    -> rebuilds on change and serves http://localhost:5173
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';

const root = path.dirname(new URL(import.meta.url).pathname);
const args = process.argv.slice(2);
const serve = args.includes('--serve');
const watch = serve && !args.includes('--no-watch');
const dev = serve;

// 1) Menu photos: any file in src/assets/menu named <product-id>.(jpg|png|webp) is picked up automatically.
function genMenuPhotos() {
  const dir = path.join(root, 'src/assets/menu');
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort() : [];
  const groups = {};
  for (const f of files) {
    const m = f.match(/^(.+?)(?:[-_](\d))?\.(jpe?g|png|webp)$/i); // "pizza.jpg", "pizza-2.jpg"
    const id = m[1];
    (groups[id] ||= []).push(f);
  }
  for (const id of Object.keys(groups)) groups[id].sort((a, b) => (/[-_]\d\./.test(a) ? 1 : 0) - (/[-_]\d\./.test(b) ? 1 : 0) || a.localeCompare(b));
  let out = '// AUTO-GENERATED by build.mjs — do not edit. Drop photos in src/assets/menu/<product-id>.jpg (extra photos: <product-id>-2.jpg)\n';
  const names = [];
  files.forEach((f, i) => { out += `import p${i} from '../assets/menu/${f}';\n`; names.push([f, `p${i}`]); });
  out += 'export const menuPhotos: Record<string, string[]> = {\n';
  for (const [id, fs_] of Object.entries(groups)) {
    out += `  ${JSON.stringify(id)}: [${fs_.map((f) => names.find((n) => n[0] === f)[1]).join(', ')}],\n`;
  }
  out += '};\n';
  const target = path.join(root, 'src/data/menuPhotos.generated.ts');
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== out) fs.writeFileSync(target, out); // only if changed (avoids watch loops)
}

function writeHtml(result) {
  const js = result.outputFiles.find((f) => f.path.endsWith('.js')).text.replace(/<\/script/gi, '<\\/script');
  const cssFile = result.outputFiles.find((f) => f.path.endsWith('.css'));
  const css = cssFile ? cssFile.text : '';
  let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  html = html.replace('<!--INLINE_CSS-->', () => `<style>${css}</style>`).replace('<!--INLINE_JS-->', () => `<script>${js}</script>`);
  fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
  fs.writeFileSync(path.join(root, 'dist/index.html'), html);
  console.log(`dist/index.html  ${(html.length / 1024).toFixed(0)} KB  ${new Date().toLocaleTimeString()}`);
}

const options = {
  entryPoints: [path.join(root, 'src/main.tsx')],
  bundle: true,
  write: false,
  outdir: path.join(root, 'dist'),
  format: 'iife',
  target: 'es2020',
  jsx: 'automatic',
  minify: !dev,
  sourcemap: false,
  loader: { '.jpg': 'dataurl', '.jpeg': 'dataurl', '.png': 'dataurl', '.webp': 'dataurl', '.svg': 'dataurl' },
  define: { 'process.env.NODE_ENV': dev ? '"development"' : '"production"' },
  logLevel: 'warning',
  plugins: [{ name: 'html', setup(b) { b.onStart(genMenuPhotos); b.onEnd((r) => { if (!r.errors.length) writeHtml(r); }); } }],
};

if (serve) {
  const ctx = await esbuild.context(options);
  await ctx.rebuild();
  if (watch) await ctx.watch();
  http.createServer((req, res) => {
    const html = fs.readFileSync(path.join(root, 'dist/index.html'));
    res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' }); res.end(html);
  }).listen(5173, () => console.log('Basha site: http://localhost:5173'));
} else {
  genMenuPhotos();
  const result = await esbuild.build(options);
  if (result.errors.length) process.exit(1);
}
